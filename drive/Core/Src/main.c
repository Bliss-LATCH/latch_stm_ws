		static int16_t last_rpm = 0;

		uint32_t current_time = HAL_GetTick();
		uint32_t dt = current_time - previous_time;

		if (dt == 0) return last_rpm;

		uint16_t current_count = __HAL_TIM_GET_COUNTER(&htim4);
		int16_t velocity_ticks = (int16_t)(current_count - previous_count);

